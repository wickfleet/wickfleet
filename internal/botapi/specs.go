// generatedMark starts every file the generator writes; anything else in
// strategies/ is hand-written and a spec never overwrites it.
const generatedMark = "# Generated by wickfleet from a strategy spec"

// SpecRoutes registers /hub/api/specs.
func (a API) SpecRoutes(mux Mux) {
	mux.HandleFunc("GET /hub/api/specs", a.specList)
	mux.HandleFunc("GET /hub/api/specs/{name}", a.specGet)
	mux.HandleFunc("POST /hub/api/specs/check", a.specCheck)
	mux.HandleFunc("POST /hub/api/specs/draft", a.specDraft)
	mux.HandleFunc("GET /hub/api/specs/draft/{id}", a.specDraftGet)
	mux.HandleFunc("PUT /hub/api/specs/{name}", a.specPut)
	mux.HandleFunc("DELETE /hub/api/specs/{name}", a.specDelete)
}

// SpecView is one spec in a listing.
type SpecView struct {
	Name        string   `json:"name"`
	Description string   `json:"description,omitempty"`
	Author      string   `json:"author,omitempty"`
	Timeframe   string   `json:"timeframe"`
	Model       bool     `json:"model"`
	UsedBy      []string `json:"used_by"`
	Editable    bool     `json:"editable"`
}

func (a API) readSpec(name string) (strategy.Spec, bool, error) {
	raw, err := os.ReadFile(filepath.Join(a.RegistryDir, "strategies", name+".json"))
	if errors.Is(err, os.ErrNotExist) {
		return strategy.Spec{}, false, nil
	}
	if err != nil {
		return strategy.Spec{}, false, err
	}
	s, err := strategy.Parse(raw)
	return s, true, err
}

// headSpec reads the spec at the remote head, so a write decides on what is
// committed, not on a checkout that may be a minute behind.
func (a API) headSpec(r *http.Request, name string) (strategy.Spec, bool, error) {
	raw, err := a.Store.Read(r.Context(), "strategies/"+name+".json")
	if errors.Is(err, os.ErrNotExist) {
		return strategy.Spec{}, false, nil
	}
	if err != nil {
		return strategy.Spec{}, false, err
	}
	s, err := strategy.Parse(raw)
	return s, true, err
}

// usedBy lists the bots running this strategy file.
func (a API) usedBy(name string) []registry.Bot {
	var out []registry.Bot
	for _, b := range a.Bots() {
		if b.StrategyFile == name+".py" {
			out = append(out, b)
		}
	}
	return out
}

// mayChange: a managed bot's strategy never (its controller writes it), nor a
// reserved author's. Else admins always, others when they wrote it and only their own bots use it.
func mayChange(id authz.Identity, s strategy.Spec, users []registry.Bot, reserved string) (bool, string) {
	for _, b := range users {
		if b.Managed != "" {
			return false, "managed bot " + b.Name + " runs this strategy, only its controller changes it"
		}
	}
	if reserved != "" && s.Author == reserved {
		return false, "this strategy belongs to " + reserved + ", only it changes the strategy"
	}
	if id.Role == authz.Admin {
		return true, ""
	}
	if id.Role < authz.Operator {
		return false, "operators and admins only"
	}
	if s.Author != id.User {
		return false, "only " + s.Author + " or an admin may change this strategy"
	}
	for _, b := range users {
		if b.Owner != id.User {
			return false, "bot " + b.Name + " of " + b.Owner + " runs this strategy"
		}
	}
	return true, ""
}

func names(bots []registry.Bot) []string {
	out := []string{}
	for _, b := range bots {
		out = append(out, b.Name)
	}
	return out
}

func (a API) specList(w http.ResponseWriter, r *http.Request) {
	id := authz.FromHeaders(r.Header)
	if id.Role == authz.None {
		fail(w, http.StatusForbidden, "no wickfleet role")
		return
	}
	files, _ := filepath.Glob(filepath.Join(a.RegistryDir, "strategies", "*.json"))
	sort.Strings(files)
	out := []SpecView{}
	for _, f := range files {
		name := strings.TrimSuffix(filepath.Base(f), ".json")
		s, ok, err := a.readSpec(name)
		if !ok || err != nil {
			continue
		}
		users := a.usedBy(name)
		can, _ := mayChange(id, s, users, a.ReservedAuthor)
		out = append(out, SpecView{Name: s.Name, Description: s.Description, Author: s.Author,
			Timeframe: s.Timeframe, Model: s.Model != nil, UsedBy: names(users), Editable: can})
	}
	jsonOut(w, http.StatusOK, map[string]any{"specs": out, "can_create": id.Role >= authz.Operator && a.Store != nil,
		"can_draft": id.Role >= authz.Operator && a.Drafts != nil})
}

func (a API) specGet(w http.ResponseWriter, r *http.Request) {
	id := authz.FromHeaders(r.Header)
	if id.Role == authz.None {
		fail(w, http.StatusForbidden, "no wickfleet role")
		return
	}
	if !strategy.ValidName(r.PathValue("name")) {
		fail(w, http.StatusNotFound, "no such strategy spec")
		return
	}
	s, ok, err := a.readSpec(r.PathValue("name"))
	if !ok || err != nil {
		fail(w, http.StatusNotFound, "no such strategy spec")
		return
	}
	src, _ := s.Python()
	users := a.usedBy(s.Name)
	can, _ := mayChange(id, s, users, a.ReservedAuthor)
	jsonOut(w, http.StatusOK, map[string]any{"spec": s, "describe": s.Describe(), "python": src,
		"used_by": names(users), "editable": can})
}

func decodeSpec(w http.ResponseWriter, r *http.Request) (strategy.Spec, bool) {
	if !strings.HasPrefix(r.Header.Get("Content-Type"), "application/json") {
		fail(w, http.StatusUnsupportedMediaType, "JSON only")
		return strategy.Spec{}, false
	}
	raw, err := io.ReadAll(io.LimitReader(r.Body, 64<<10))
	if err != nil {
		fail(w, http.StatusBadRequest, err.Error())
		return strategy.Spec{}, false
	}
	s, err := strategy.Parse(raw)
	if err != nil {
		fail(w, http.StatusBadRequest, err.Error())
		return strategy.Spec{}, false
	}
	return s, true
}

func (a API) specGuard(w http.ResponseWriter, r *http.Request) (authz.Identity, bool) {
	if r.Header.Get(CSRFHeader) != "1" {
		fail(w, http.StatusForbidden, "missing "+CSRFHeader)
		return authz.Identity{}, false
	}
	id := authz.FromHeaders(r.Header)
	if id.Role < authz.Operator {
		fail(w, http.StatusForbidden, "operators and admins only")
		return id, false
	}
	return id, true
}

// specCheck validates without writing: the readback and code to review.
func (a API) specCheck(w http.ResponseWriter, r *http.Request) {
	if _, ok := a.specGuard(w, r); !ok {
		return
	}
	s, ok := decodeSpec(w, r)
	if !ok {
		return
	}
	src, _ := s.Python()
	jsonOut(w, http.StatusOK, map[string]any{"ok": true, "describe": s.Describe(), "python": src})
}

func (a API) specPut(w http.ResponseWriter, r *http.Request) {
	id, ok := a.specGuard(w, r)
	if !ok {
		return
	}
	if a.Store == nil {
		fail(w, http.StatusServiceUnavailable, "registry writes are not configured")
		return
	}
	s, ok := decodeSpec(w, r)
	if !ok {
		return
	}
	if s.Name != r.PathValue("name") {
		fail(w, http.StatusBadRequest, "the spec's name must match the path")
		return
	}
	old, exists, err := a.headSpec(r, s.Name)
	if err != nil {
		fail(w, http.StatusConflict, "the stored spec cannot be read: "+err.Error())
		return
	}
	if exists {
		if can, why := mayChange(id, old, a.usedBy(s.Name), a.ReservedAuthor); !can {
			fail(w, http.StatusForbidden, why)
			return
		}
		s.Author = old.Author
	} else {
		if src, err := a.Store.Read(r.Context(), "strategies/"+s.Name+".py"); err == nil && !strings.HasPrefix(string(src), generatedMark) {
			fail(w, http.StatusConflict, "a hand-written strategy "+s.Name+".py exists; pick another name")
			return
		}
		s.Author = id.User
	}
	src, err := s.Python()
	if err != nil {
		fail(w, http.StatusBadRequest, err.Error())
		return
	}
	spec, _ := json.MarshalIndent(s, "", "  ")
	verb := "adds"
	if exists {
		verb = "changes"
	}
	err = a.Store.ChangeAll(r.Context(), map[string][]byte{
		"strategies/" + s.Name + ".json": append(spec, '\n'),
		"strategies/" + s.Name + ".py":   []byte(src),
	}, fmt.Sprintf("feat: %s %s strategy %s", id.User, verb, s.Name), author(id))
	if errors.Is(err, gitstore.ErrNoChange) {
		jsonOut(w, http.StatusOK, map[string]string{"result": "unchanged"})
		return
	}
	if err != nil {
		fail(w, http.StatusBadGateway, "commit failed")
		return
	}
	jsonOut(w, http.StatusAccepted, map[string]string{"result": verb, "note": "usable after the next sync, about a minute",
		"describe": s.Describe()})
}

func (a API) specDelete(w http.ResponseWriter, r *http.Request) {
	id, ok := a.specGuard(w, r)
	if !ok {
		return
	}
	if a.Store == nil {
		fail(w, http.StatusServiceUnavailable, "registry writes are not configured")
		return
	}
	name := r.PathValue("name")
	if !strategy.ValidName(name) {
		fail(w, http.StatusNotFound, "no such strategy spec")
		return
	}
	s, exists, err := a.headSpec(r, name)
	if !exists || err != nil {
		fail(w, http.StatusNotFound, "no such strategy spec")
		return
	}
	users := a.usedBy(name)
	if can, why := mayChange(id, s, users, a.ReservedAuthor); !can {
		fail(w, http.StatusForbidden, why)
		return
	}
	if len(users) > 0 {
		fail(w, http.StatusConflict, "still used by "+strings.Join(names(users), ", "))
		return
	}
	err = a.Store.ChangeAll(r.Context(), map[string][]byte{
		"strategies/" + name + ".json": nil, "strategies/" + name + ".py": nil,
	}, fmt.Sprintf("feat: %s removes strategy %s", id.User, name), author(id))
	if err != nil && !errors.Is(err, gitstore.ErrNoChange) {
		fail(w, http.StatusBadGateway, "commit failed")
		return
	}
	jsonOut(w, http.StatusAccepted, map[string]string{"result": "removed"})
}

// Drafter turns a sentence into a checked spec (internal/drafter).
type Drafter interface {
	Draft(ctx context.Context, sentence string) (drafter.Result, error)
}

// DraftJob is one sentence being drafted. A CPU draft takes longer than the
// edge proxy holds a request, so the API answers at once and the UI polls.
type DraftJob struct {
	ID      string          `json:"id"`
	Owner   string          `json:"owner"`
	State   string          `json:"state"` // running | done | failed
	Error   string          `json:"error,omitempty"`
	Result  *drafter.Result `json:"result,omitempty"`
	Started time.Time       `json:"started"`
}

// Drafts runs one draft at a time and keeps results for a while.
type Drafts struct {
	Drafter Drafter
	Timeout time.Duration
	Keep    time.Duration

	mu      sync.Mutex
	jobs    map[string]*DraftJob
	running bool
}

// NewDrafts wraps a drafter; nil means drafting is off.
func NewDrafts(d Drafter) *Drafts {
	if d == nil {
		return nil
	}
	return &Drafts{Drafter: d, Timeout: 4 * time.Minute, Keep: 30 * time.Minute, jobs: map[string]*DraftJob{}}
}

// ErrDraftBusy: one draft runs at a time; a CPU model takes the whole box.
var ErrDraftBusy = errors.New("a draft is already running, try again in a minute")

// Start queues nothing: it runs now or refuses.
func (d *Drafts) Start(owner, sentence string) (DraftJob, error) {
	d.mu.Lock()
	defer d.mu.Unlock()
	if d.running {
		return DraftJob{}, ErrDraftBusy
	}
	for id, j := range d.jobs {
		if j.State != "running" && time.Since(j.Started) > d.Keep {
			delete(d.jobs, id)
		}
	}
	b := make([]byte, 6)
	_, _ = rand.Read(b)
	j := &DraftJob{ID: "d" + hex.EncodeToString(b), Owner: owner, State: "running", Started: time.Now()}
	d.jobs[j.ID], d.running = j, true
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), d.Timeout)
		defer cancel()
		res, err := d.Drafter.Draft(ctx, sentence)
		d.mu.Lock()
		defer d.mu.Unlock()
		d.running = false
		if err != nil {
			j.State, j.Error = "failed", err.Error()
			return
		}
		j.State, j.Result = "done", &res
	}()
	return *j, nil
}

// Get returns a copy of the job if the caller may see it.
func (d *Drafts) Get(id authz.Identity, jobID string) (DraftJob, bool) {
	d.mu.Lock()
	defer d.mu.Unlock()
	j, ok := d.jobs[jobID]
	if !ok || (id.Role != authz.Admin && j.Owner != id.User) {
		return DraftJob{}, false
	}
	return *j, true
}

// specDraft starts a draft. Nothing is saved: the editor shows the result for
// review and the usual check and save follow.
func (a API) specDraft(w http.ResponseWriter, r *http.Request) {
	id, ok := a.specGuard(w, r)
	if !ok {
		return
	}
	if a.Drafts == nil {
		fail(w, http.StatusServiceUnavailable, "no drafting model is configured on this instance")
		return
	}
	var in struct {
		Sentence string `json:"sentence"`
	}
	dec := json.NewDecoder(io.LimitReader(r.Body, 8<<10))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&in); err != nil {
		fail(w, http.StatusBadRequest, "bad body: "+err.Error())
		return
	}
	if n := len(strings.TrimSpace(in.Sentence)); n < 10 || n > 1000 {
		fail(w, http.StatusBadRequest, "describe the strategy in 10 to 1000 characters")
		return
	}
	j, err := a.Drafts.Start(id.User, in.Sentence)
	if errors.Is(err, ErrDraftBusy) {
		fail(w, http.StatusTooManyRequests, err.Error())
		return
	}
	jsonOut(w, http.StatusAccepted, j)
}

func (a API) specDraftGet(w http.ResponseWriter, r *http.Request) {
	id := authz.FromHeaders(r.Header)
	if id.Role < authz.Operator || a.Drafts == nil {
		fail(w, http.StatusNotFound, "no such draft")
		return
	}
	j, ok := a.Drafts.Get(id, r.PathValue("id"))
	if !ok {
		fail(w, http.StatusNotFound, "no such draft")
		return
	}
	jsonOut(w, http.StatusOK, j)
}
