package strategy

import (
	"fmt"
	"strconv"
	"strings"
)

func num(f float64) string { return strconv.FormatFloat(f, 'g', -1, 64) }

// flt always reads as a Python float; talib rejects an int where it wants one.
func flt(f float64) string {
	s := num(f)
	if !strings.ContainsAny(s, ".e") {
		s += ".0"
	}
	return s
}

func col(ref string) string { return `df["` + ref + `"]` }

// Python returns the strategy source for a valid spec.
func (s Spec) Python() (string, error) {
	if err := s.Validate(); err != nil {
		return "", err
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	needTA := s.Model != nil
	for _, in := range s.Indicators {
		switch in.Kind {
		case "sma", "highest", "lowest":
		default:
			needTA = true
		}
	}
	w("# Generated by wickfleet from a strategy spec (v%d). Change the spec, not this file.\n", Version)
	if s.Description != "" {
		w("# %s\n", s.Description)
	}
	if s.Model != nil {
		w("# Model features follow freqtrade's FreqAI example strategy.\n")
	}
	if needTA {
		w("import talib.abstract as ta\n")
	}
	if s.Model != nil {
		w("from technical import qtpylib\n")
	}
	w("from freqtrade.strategy import IStrategy\nfrom pandas import DataFrame\n\n\n")
	w("class %s(IStrategy):\n", s.Name)
	w("    INTERFACE_VERSION = 3\n")
	w("    timeframe = %q\n", s.Timeframe)
	if len(s.ROI) == 0 {
		w("    minimal_roi = {\"0\": 100}\n")
	} else {
		var parts []string
		for _, k := range s.roiKeys() {
			parts = append(parts, fmt.Sprintf("%q: %s", k, num(s.ROI[k])))
		}
		w("    minimal_roi = {%s}\n", strings.Join(parts, ", "))
	}
	w("    stoploss = %s\n", num(s.Stoploss))
	if t := s.Trailing; t != nil {
		w("    trailing_stop = True\n    trailing_stop_positive = %s\n", num(t.Positive))
		if t.Offset > 0 {
			w("    trailing_stop_positive_offset = %s\n", num(t.Offset))
		}
		if t.OnlyOffsetReached {
			w("    trailing_only_offset_is_reached = True\n")
		}
	}
	w("    startup_candle_count = %d\n\n", s.Startup())

	if s.Model != nil {
		b.WriteString(modelPython)
	}
	w("    def populate_indicators(self, df: DataFrame, metadata: dict) -> DataFrame:\n")
	if s.Model != nil {
		w("        df = self.freqai.start(df, metadata, self)\n")
	}
	for _, in := range s.Indicators {
		for _, line := range in.python() {
			w("        %s\n", line)
		}
	}
	w("        return df\n\n")
	w("    def populate_entry_trend(self, df: DataFrame, metadata: dict) -> DataFrame:\n")
	w("        df.loc[%s, \"enter_long\"] = 1\n        return df\n\n", s.Entry.python())
	w("    def populate_exit_trend(self, df: DataFrame, metadata: dict) -> DataFrame:\n")
	w("        df.loc[%s, \"exit_long\"] = 1\n        return df\n", s.Exit.python())
	if g := s.EntryGuard; g != nil {
		w("\n    def confirm_trade_entry(self, pair: str, order_type: str, amount: float, rate: float,\n")
		w("                            time_in_force: str, current_time, entry_tag, side: str, **kwargs) -> bool:\n")
		w("        df, _ = self.dp.get_analyzed_dataframe(pair, self.timeframe)\n")
		w("        return bool(rate <= df.iloc[-1][\"close\"] * (1 + %s))\n", flt(g.MaxAboveClose))
	}
	return b.String(), nil
}

func (in Indicator) python() []string {
	shift := ""
	if in.Shift > 0 {
		shift = fmt.Sprintf(".shift(%d)", in.Shift)
	}
	src := col(in.Source)
	id := col(in.ID)
	sub := func(f string) string { return col(in.ID + "." + f) }
	switch in.Kind {
	case "sma":
		return []string{fmt.Sprintf("%s = %s.rolling(%d).mean()%s", id, src, in.Period, shift)}
	case "highest":
		return []string{fmt.Sprintf("%s = %s.rolling(%d).max()%s", id, src, in.Period, shift)}
	case "lowest":
		return []string{fmt.Sprintf("%s = %s.rolling(%d).min()%s", id, src, in.Period, shift)}
	case "ema", "tema":
		return []string{fmt.Sprintf("%s = ta.%s(df, timeperiod=%d, price=%q)%s", id, strings.ToUpper(in.Kind), in.Period, in.Source, shift)}
	case "rsi":
		return []string{fmt.Sprintf("%s = ta.RSI(df, timeperiod=%d, price=%q)", id, in.Period, in.Source)}
	case "atr", "adx":
		return []string{fmt.Sprintf("%s = ta.%s(df, timeperiod=%d)", id, strings.ToUpper(in.Kind), in.Period)}
	case "bollinger":
		return []string{
			fmt.Sprintf("_bb = ta.BBANDS(df, timeperiod=%d, nbdevup=%s, nbdevdn=%s, price=%q)", in.Period, flt(in.StdDev), flt(in.StdDev), in.Source),
			fmt.Sprintf(`%s, %s, %s = _bb["upperband"], _bb["middleband"], _bb["lowerband"]`, sub("upper"), sub("middle"), sub("lower")),
		}
	case "macd":
		return []string{
			fmt.Sprintf("_macd = ta.MACD(df, fastperiod=%d, slowperiod=%d, signalperiod=%d, price=%q)", in.Fast, in.Slow, in.Signal, in.Source),
			fmt.Sprintf(`%s, %s, %s = _macd["macd"], _macd["macdsignal"], _macd["macdhist"]`, sub("macd"), sub("signal"), sub("hist")),
		}
	case "stoch":
		return []string{
			fmt.Sprintf("_st = ta.STOCH(df, fastk_period=%d, slowk_period=%d, slowd_period=%d)", in.Period, in.SmoothK, in.SmoothD),
			fmt.Sprintf(`%s, %s = _st["slowk"], _st["slowd"]`, sub("k"), sub("d")),
		}
	}
	return nil // unreachable after Validate
}

// Model outputs keep FreqAI's own column names.
var modelCols = map[string]string{"prediction": "&-s_close", "do_predict": "do_predict"}

func (o Operand) python() string {
	if o.Num != nil {
		return num(*o.Num)
	}
	if c, ok := modelCols[o.Ref]; ok {
		return col(c)
	}
	return col(o.Ref)
}

// shifted is the operand one candle back; a number stays itself.
func (o Operand) shifted() string {
	if o.Num != nil {
		return num(*o.Num)
	}
	return o.python() + ".shift(1)"
}

func (c Condition) python() string {
	l, r := c.Left.python(), c.Right.python()
	switch c.Op {
	case "crosses_above":
		return fmt.Sprintf("(%s > %s) & (%s.shift(1) <= %s)", l, r, l, c.Right.shifted())
	case "crosses_below":
		return fmt.Sprintf("(%s < %s) & (%s.shift(1) >= %s)", l, r, l, c.Right.shifted())
	case "rising":
		return fmt.Sprintf("%s > %s.shift(%d)", l, l, c.Bars)
	case "falling":
		return fmt.Sprintf("%s < %s.shift(%d)", l, l, c.Bars)
	}
	return fmt.Sprintf("%s %s %s", l, c.Op, r)
}

func (g Group) python() string {
	conds, join := g.All, " & "
	if len(g.Any) > 0 {
		conds, join = g.Any, " | "
	}
	parts := make([]string, len(conds))
	for i, c := range conds {
		parts[i] = "(" + c.python() + ")"
	}
	return strings.Join(parts, join)
}

// modelPython is the fixed feature set and target. FreqAI expands every
// column starting with % per window, timeframe and shift from the bot config;
// the target is the mean close over the next label_period_candles, as a return.
const modelPython = `    def feature_engineering_expand_all(self, dataframe: DataFrame, period: int, metadata: dict, **kwargs) -> DataFrame:
        dataframe["%-rsi-period"] = ta.RSI(dataframe, timeperiod=period)
        dataframe["%-mfi-period"] = ta.MFI(dataframe, timeperiod=period)
        dataframe["%-adx-period"] = ta.ADX(dataframe, timeperiod=period)
        dataframe["%-sma-period"] = ta.SMA(dataframe, timeperiod=period)
        dataframe["%-ema-period"] = ta.EMA(dataframe, timeperiod=period)
        bands = qtpylib.bollinger_bands(qtpylib.typical_price(dataframe), window=period, stds=2.2)
        dataframe["bb_lowerband-period"] = bands["lower"]
        dataframe["bb_middleband-period"] = bands["mid"]
        dataframe["bb_upperband-period"] = bands["upper"]
        dataframe["%-bb_width-period"] = (bands["upper"] - bands["lower"]) / bands["mid"]
        dataframe["%-close-bb_lower-period"] = dataframe["close"] / bands["lower"]
        dataframe["%-roc-period"] = ta.ROC(dataframe, timeperiod=period)
        dataframe["%-relative_volume-period"] = dataframe["volume"] / dataframe["volume"].rolling(period).mean()
        return dataframe

    def feature_engineering_expand_basic(self, dataframe: DataFrame, metadata: dict, **kwargs) -> DataFrame:
        dataframe["%-pct-change"] = dataframe["close"].pct_change()
        dataframe["%-raw_volume"] = dataframe["volume"]
        dataframe["%-raw_price"] = dataframe["close"]
        return dataframe

    def feature_engineering_standard(self, dataframe: DataFrame, metadata: dict, **kwargs) -> DataFrame:
        dataframe["%-day_of_week"] = dataframe["date"].dt.dayofweek
        dataframe["%-hour_of_day"] = dataframe["date"].dt.hour
        return dataframe

    def set_freqai_targets(self, dataframe: DataFrame, metadata: dict, **kwargs) -> DataFrame:
        n = self.freqai_info["feature_parameters"]["label_period_candles"]
        dataframe["&-s_close"] = dataframe["close"].shift(-n).rolling(n).mean() / dataframe["close"] - 1
        return dataframe

`
